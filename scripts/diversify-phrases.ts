function applyFrame(action: TextReading, selected: Frame): TextReading {
  return phrase(
    `${selected.prefix.text}${action.text}${selected.suffix.text}`,
    `${selected.prefix.reading}${action.reading}${selected.suffix.reading}`,
  );
}

export function diversifyPhrases(catalog: ContentCatalog): ContentCatalog {
  const used = new Set<string>();
  const phrases = catalog.phrases.map((currentPhrase) => {
    const mission = catalog.missions.find((item) => item.id === currentPhrase.missionId);
    if (!mission) throw new Error(`Mission not found for ${currentPhrase.id}`);
    const district = catalog.districts.find((item) => item.id === mission.districtId);
    if (!district) throw new Error(`District not found for ${currentPhrase.id}`);
    const zoneSource = zoneSources.find((zone) => zone.id === mission.zoneId);
    const districtSource = zoneSource?.districts.find((item) => item.name === district.name);
    if (!districtSource) throw new Error(`District source not found for ${currentPhrase.id}`);

    const suffixes = sceneSuffixes[district.name];
    if (!suffixes || suffixes.length !== districtSource.words.length) {
      throw new Error(`Natural scene definitions are incomplete for ${district.name}`);
    }
    const scenes = districtSource.words.map((word, index) => {
      const suffix = suffixes[index]!;
      return phrase(`${word.text}${suffix[0]}`, `${word.reading}${suffix[1]}`);
    });

    const stageIndex = (mission.number - 1) % missionStages.length;
    const rotatedScenes = scenes.map((_, index) => scenes[(stageIndex + index) % scenes.length]!);
    const frames = framesFor(mission.level, { text: district.name, reading: district.reading });
    const orderIndex = currentPhrase.order - 1;
    const action = rotatedScenes[orderIndex % rotatedScenes.length]!;
    const selectedFrame = frames[orderIndex];
    if (!selectedFrame) throw new Error(`Phrase frame not found for ${currentPhrase.id}`);
    const replacement = applyFrame(action, selectedFrame);

    let finalText = replacement.text;
    let finalReading = replacement.reading;
    if (used.has(finalText)) {
      finalText = `${district.name}で${finalText}`;
      finalReading = `${district.reading}で${finalReading}`;
    }
    if (used.has(finalText)) {
      const stage = missionStages[stageIndex]!;
      finalText = `${stage.rewardSuffix.text}で${finalText}`;
      finalReading = `${stage.rewardSuffix.reading}で${finalReading}`;
    }
    if (used.has(finalText)) throw new Error(`Duplicate diversified phrase: ${finalText}`);
    used.add(finalText);

    return {
      ...currentPhrase,
      text: finalText,
      reading: finalReading,
      romanization: toCanonicalRoman(finalReading),
    };
  });

  return { ...catalog, version: 3, phrases };
}
